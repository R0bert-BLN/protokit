// Derived files: agent adapters, shared hub and review files, the site registry (hub/site.js).
import fs from 'node:fs';
import path from 'node:path';
import { TEMPLATE, abs, read, readOpt, update, write, config, projects, manifest, frontMatter, walk, rel, fail } from './util.mjs';

const MARK = 'Generated by pk sync';
export const SHARED = ['js/hub.js', 'css/hub.css', 'js/review.js', 'css/review.css', 'screens/_planned.html'];
const SITE_SHARED = { 'hub/hub.js': 'js/hub.js', 'hub/hub.css': 'css/hub.css' };

// Tool → adapters. "agents" is the shared .agents/skills folder (Agent Skills standard).
export const TOOLS = {
  claude: { name: 'Claude Code', adapters: ['claude'] },
  codex: { name: 'Codex CLI', adapters: ['agents'] },
  generic: { name: 'Any tool that reads AGENTS.md and .agents/skills', adapters: ['agents'] },
  opencode: { name: 'opencode', adapters: ['agents', 'opencode'] },
  pi: { name: 'pi', adapters: ['agents', 'pi'] },
  gemini: { name: 'Gemini CLI', adapters: ['agents', 'gemini'] },
  cursor: { name: 'Cursor', adapters: ['agents', 'cursor'] },
  copilot: { name: 'GitHub Copilot (VS Code)', adapters: ['agents', 'copilot'] },
};

// Kit skills, then .ai/local/skills (same name replaces the kit skill)
export function skills() {
  const out = new Map();
  for (const dir of ['.ai/skills', '.ai/local/skills']) {
    if (!fs.existsSync(abs(dir))) continue;
    for (const name of fs.readdirSync(abs(dir)).sort()) {
      const file = `${dir}/${name}/SKILL.md`;
      if (!fs.existsSync(abs(file))) continue;
      const text = read(file);
      const { meta, body } = frontMatter(text);
      const line = (k) => text.match(new RegExp(`^${k}:.*$`, 'm'))?.[0] || '';
      out.set(name, { name, file, meta, body: body.replace(/^\n+/, ''), description: line('description'), hint: line('argument-hint'), manual: line('disable-model-invocation') });
    }
  }
  return [...out.values()];
}

export const rules = () => ['.ai/rules', '.ai/local/rules']
  .flatMap((dir) => (fs.existsSync(abs(dir)) ? fs.readdirSync(abs(dir)).filter((f) => f.endsWith('.md')).sort().map((f) => `${dir}/${f}`) : []));

const fm = (...lines) => `---\n${lines.filter(Boolean).join('\n')}\n---\n`;
const note = (s) => `<!-- ${MARK} from ${s.file}: edit the source, not this copy. -->`;
const pointer = (s, args) => `Follow \`${s.file}\` exactly${args ? ` for: ${args}` : ''}. Read the rules in \`AGENTS.md\` first if they are not loaded yet.\n`;
const hintText = (s) => s.hint.replace(/^argument-hint:\s*/, '').replace(/^"|"$/g, '');
const descText = (s) => s.meta.description || '';

const ADAPTERS = {
  claude: () => ({
    'CLAUDE.md': [
      `<!-- ${MARK}: lists AGENTS.md and the rules for Claude Code. -->`,
      '@AGENTS.md',
      ...rules().map((r) => `@${r}`),
      '',
      'Claude Code: the rules above are already loaded; do not read them again. The skills in `.claude/skills/` (also `/<name>`) are generated copies: edit `.ai/skills/` (or `.ai/local/skills/`), then run `node scripts/pk.mjs sync`.',
      '',
    ].join('\n'),
    ...Object.fromEntries(skills().map((s) => [`.claude/skills/${s.name}/SKILL.md`,
      `${fm(`name: ${s.name}`, s.description, s.hint, s.manual)}${note(s)}\n${s.body.trimEnd()}\n\nArguments: $ARGUMENTS\n`])),
  }),
  agents: () => Object.fromEntries(skills().map((s) => [`.agents/skills/${s.name}/SKILL.md`,
    `${fm(`name: ${s.name}`, s.description)}${note(s)}\n${s.body.trimEnd()}\n`])),
  opencode: () => Object.fromEntries(skills().map((s) => [`.opencode/commands/${s.name}.md`,
    `${fm(`description: ${JSON.stringify(descText(s).split('. ')[0])}`)}${note(s)}\n${pointer(s, '$ARGUMENTS')}`])),
  pi: () => Object.fromEntries(skills().map((s) => [`.pi/prompts/${s.name}.md`,
    `${fm(`description: ${JSON.stringify(descText(s).split('. ')[0])}`, s.hint && `argument-hint: "${hintText(s)}"`)}${note(s)}\n${pointer(s, '$ARGUMENTS')}`])),
  cursor: () => Object.fromEntries(skills().map((s) => [`.cursor/commands/${s.name}.md`,
    `${note(s)}\n${pointer(s)}The arguments are the text after the command${s.hint ? ` (${hintText(s)})` : ''}.\n`])),
  copilot: () => Object.fromEntries(skills().map((s) => [`.github/prompts/${s.name}.prompt.md`,
    `${fm(`description: ${JSON.stringify(descText(s).split('. ')[0])}`, 'agent: agent')}${note(s)}\n${pointer(s, '${input:arguments}')}`])),
  gemini: () => {
    let settings = {};
    try { settings = JSON.parse(readOpt('.gemini/settings.json') || '{}'); } catch {}
    const names = new Set([...(settings.context?.fileName ? [].concat(settings.context.fileName) : []), 'AGENTS.md']);
    settings.context = { ...settings.context, fileName: [...names] };
    return { '.gemini/settings.json': `${JSON.stringify(settings, null, 2)}\n` };
  },
};

// Files written by an adapter that is no longer enabled, or by a skill that no longer exists
const generatedFiles = () => [
  ...['CLAUDE.md'].filter((f) => readOpt(f).includes(MARK)),
  ...['.claude/skills', '.agents/skills', '.opencode/commands', '.pi/prompts', '.cursor/commands', '.github/prompts']
    .flatMap((d) => walk(d).map(rel).filter((f) => readOpt(f).includes(MARK))),
];

export const enabledTools = () => {
  const list = config().agents ?? ['claude'];
  for (const t of list) if (!TOOLS[t]) fail(`protokit.json: unknown agent '${t}'. Known: ${Object.keys(TOOLS).join(', ')}.`);
  return list;
};

function adapterFiles() {
  const names = new Set(enabledTools().flatMap((t) => TOOLS[t].adapters));
  return Object.assign({}, ...[...names].map((n) => ADAPTERS[n]()));
}

function siteRegistry() {
  const cfg = config();
  const list = projects().map((slug) => {
    const M = manifest(slug) || { modules: [] };
    const readme = frontMatter(readOpt(`projects/${slug}/README.md`)).meta;
    const screens = (M.modules || []).flatMap((m) => m.screens || []);
    return {
      slug,
      title: M.title || slug,
      description: M.description || '',
      status: M.status || readme.status || 'Brief',
      updated: M.updated || readme.updated || '',
      device: M.device || '',
      themes: M.themes || ['light'],
      modules: (M.modules || []).length,
      screens: screens.length,
      built: screens.filter((s) => s.built).length,
    };
  }).sort((a, b) => b.updated.localeCompare(a.updated) || a.title.localeCompare(b.title));
  const site = { title: cfg.title || 'protokit', description: cfg.description || '', projects: list };
  return `// ${MARK} from protokit.json and every projects/<slug>/js/project.js; do not edit.\nwindow.PK_SITE = ${JSON.stringify(site, null, 2)};\n`;
}

// Derived from sources only: always safe to rewrite
export function derived() {
  return { 'hub/site.js': siteRegistry(), ...adapterFiles() };
}

// Copies of template files: a difference may be a hand edit in the wrong place
export function copies() {
  const out = {};
  for (const [to, from] of Object.entries(SITE_SHARED)) out[to] = read(path.join(TEMPLATE, from));
  for (const slug of projects()) for (const f of SHARED) out[`projects/${slug}/${f}`] = read(path.join(TEMPLATE, f));
  return out;
}

// Writes the files; returns the paths changed or removed
export function apply(files, { prune = false } = {}) {
  const changed = Object.entries(files).filter(([p, text]) => update(p, text)).map(([p]) => p);
  if (prune) {
    for (const f of generatedFiles()) {
      if (f in files) continue;
      fs.rmSync(abs(f));
      for (let dir = path.dirname(abs(f)); dir.startsWith(abs('.')) && dir !== abs('.') && !fs.readdirSync(dir).length; dir = path.dirname(dir)) fs.rmdirSync(dir);
      changed.push(`${f} (removed)`);
    }
  }
  return changed;
}

export const stale = (files) => Object.entries(files).filter(([p, text]) => readOpt(p) !== text).map(([p]) => p);

export function syncAll() {
  return [...apply(derived(), { prune: true }), ...apply(copies())];
}

export function setAgents(tools) {
  const cfg = config();
  cfg.agents = tools;
  write('protokit.json', `${JSON.stringify(cfg, null, 2)}\n`);
}
